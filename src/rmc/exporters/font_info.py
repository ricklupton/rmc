import logging
_log = logging.getLogger(__name__)


def text_width(text: str, font_name: str, font_size: float) -> float:
    """Calculate text width for `text`."""
    widths = char_widths[font_name]
    return font_size * sum(widths.get(ord(c), 0) for c in text)


def wrap_text(text: str, width: float, font_name: str, font_size: float) -> list[str]:
    """Wrap lines from `text` to fit in `width`."""
    lines = text.splitlines()
    result = [""]
    x = 0.0
    left_over_chars = ""
    for line in lines:
        _log.debug("Left over chars (0): %s", left_over_chars)
        if left_over_chars:
            line = left_over_chars + " " + line
            left_over_chars = ""
        words = line.split()
        _log.debug("Words: %s", words)
        for j, word in enumerate(words):
            remaining = width - x
            word_width = text_width(word, font_name, font_size)
            if word_width < remaining:
                _log.debug("Word fits: %s (%.1f/%.1f)", word, x, width)
                result[-1] += word + " "
                x += word_width + text_width(" ", font_name, font_size)
            else:
                # Run out of room on this line. If it's never going to fit --
                # split the word. Otherwise leave it for next time.
                if word_width >= width:
                    _log.debug("Word too long: %s", word)
                    for i, c in enumerate(word):
                        remaining = width - x
                        char_width = text_width(c, font_name, font_size)
                        if char_width < remaining:
                            result[-1] += c
                            x += char_width
                        else:
                            left_over_chars += word[i:]
                            break
                left_over_chars += " " + " ".join(words[j+1:])
                _log.debug("Left over chars: %s", left_over_chars)
                break

        # move on to next line
        _log.debug("Filled line: %s", result[-1])
        result += [""]
        x = 0.0
    return result
